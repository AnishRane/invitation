export const messages = { en: english, mr: marathi };
export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => String(values?.[name] ?? match));
}
export function formatNumber(value: number | string, locale: Locale) {
  return new Intl.NumberFormat(locale === "mr" ? "mr-IN-u-nu-deva" : "en-IN", { useGrouping: false }).format(Number(value));
}
export function eventDate(calendarDate: string) {
  return new Date(Date.UTC(Number(calendarDate.slice(0, 4)), Number(calendarDate.slice(4, 6)) - 1, Number(calendarDate.slice(6, 8)), 12));
}
export function formatDate(calendarDate: string, locale: Locale, options: Intl.DateTimeFormatOptions = { day: "numeric", month: "long", year: "numeric" }) {
  return new Intl.DateTimeFormat(locale === "mr" ? "mr-IN-u-nu-deva" : "en-IN", { ...options, timeZone: "Asia/Kolkata" }).format(eventDate(calendarDate));
}
export function localizeError(message: string, locale: Locale) {
  const key = (Object.keys(english) as TranslationKey[]).find((key) => key.startsWith("error.") && (english[key] === message || marathi[key] === message));
  return translate(locale, key || "error.checkResponse");
}
